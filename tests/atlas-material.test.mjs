import test from "node:test";
import assert from "node:assert/strict";
import {readFileSync,mkdtempSync,writeFileSync,rmSync} from "node:fs";
import {execFileSync} from "node:child_process";
import {join} from "node:path";
import {tmpdir} from "node:os";
import {buildMaterialCirculation} from "../site/atlas/material-circulation.mjs";
import {initMaterialCirculation} from "../site/atlas/material-circulation-ui.mjs";
const file=p=>JSON.parse(readFileSync(new URL("../"+p,import.meta.url),"utf8"));
const data=file("data/atlas/circulacao-material-ciclo41.json");
const macro=file("data/atlas/macrorregioes-carcaca.json");
const networks=file("data/atlas/redes-historicas-ciclo33.json");
const chronology=file("data/atlas/cronocartografia-ciclo40.json");
const build=x=>buildMaterialCirculation(x,macro,networks,chronology);
const clone=mutate=>{const d=structuredClone(data);mutate(d);return d};
test("Atlas XLI: 24 nós materiais, 15 vínculos documentados e 12 questões abertas",()=>{
 const v=build(data);
 assert.deepEqual(v.totais,{nodos:24,vinculos:15,lacunas:12,rotas_confirmadas:0,volumes_confirmados:0});
 assert.equal(v.altera_canon,false);
 assert.equal(data.aprovacao_autoral,false);
 assert.ok(v.nodos.every(n=>n.coordenadas===null&&n.capacidade===null&&n.paginas.length));
 assert.ok(v.vinculos.every(e=>e.rota_confirmada===false&&e.geometria===null&&e.volume===null&&e.custo===null&&e.frequencia===null));
 assert.ok(v.lacunas.every(e=>e.resolvida===false&&e.rota_aferida===false));
});
test("Atlas XLI: coerção, refúgio, produção e tributos marítimos são tipos separados",()=>{
 const v=build(data),edge=id=>v.vinculos.find(x=>x.id==="vinculo:xli:"+id);
 assert.equal(edge("minerio-forjas").modalidade,"transferencia_documentada");
 assert.equal(edge("drakport-coercao").tipo,"trabalho_forcado");
 assert.match(edge("drakport-coercao").limite,/não quantificar/i);
 assert.equal(edge("eldroth-costa").tipo,"refugio");
 assert.equal(edge("eldroth-thargrid").tipo,"refugio");
 assert.equal(edge("abissais-costa").modalidade,"pressao_documentada");
 assert.match(edge("abissais-costa").limite,/não prova pagamento efetivo/i);
 assert.equal(edge("grama-fugitivos").ref_rede,null);
 assert.equal(v.nodos.find(x=>x.id==="fluxo:xli:grama-cultivos").ref_rede,null);
 assert.ok(v.guardrails.some(s=>s.includes("não são demônios")||s.includes("distintas")));
});
test("Atlas XLI: não autoriza rotas, volumes, soberanias ou membros falsos de rede",()=>{
 assert.throws(()=>build(clone(d=>d.aprovacao_autoral=true)),/proteção autoral/);
 assert.throws(()=>build(clone(d=>d.nodos[0].coordenadas=[1,2])),/posição ou capacidade/);
 assert.throws(()=>build(clone(d=>d.nodos[0].capacidade=50)),/posição ou capacidade/);
 assert.throws(()=>build(clone(d=>d.nodos[0].setor="falso")),/Nó material/);
 assert.throws(()=>build(clone(d=>d.nodos[0].ref_rede="rede-xxxiii:resistencia")),/Rede temática/);
 assert.throws(()=>build(clone(d=>d.nodos[0].ref_esfera="esfera-xxxiii:06")),/Esfera política/);
 assert.throws(()=>build(clone(d=>d.vinculos[0].rota_confirmada=true)),/rota ou métrica/);
 assert.throws(()=>build(clone(d=>d.vinculos[0].volume=42)),/rota ou métrica/);
 assert.throws(()=>build(clone(d=>d.vinculos[0].custo=9)),/rota ou métrica/);
 assert.throws(()=>build(clone(d=>d.vinculos[0].geometria={lat:1})),/rota ou métrica|geometria/);
 assert.throws(()=>build(clone(d=>d.vinculos.find(x=>x.tipo==="exigencia_tributaria").modalidade="transferencia_documentada")),/Exigência de tributo/);
 assert.throws(()=>build(clone(d=>d.vinculos.find(x=>x.tipo==="pilhagem").de="fluxo:xli:grama-cultivos")),/Pilhagens generalizadas/);
 assert.throws(()=>build(clone(d=>d.vinculos.find(x=>x.tipo==="trabalho_forcado").de="fluxo:xli:portomonte")),/Trabalho forçado/);
 assert.throws(()=>build(clone(d=>d.lacunas[0].resolvida=true)),/Lacuna material/);
 assert.throws(()=>build(clone(d=>d.vinculos.pop())),/15 vínculos/);
 assert.throws(()=>build(clone(d=>d.nodos.pop())),/24 nós/);
});
test("Atlas XLI: interface interativa funciona e evita mapas ou estimativas",()=>{
 const model=build(data),el={innerHTML:"",handlers:{},addEventListener(type,cb){this.handlers[type]=cb}};
 initMaterialCirculation(el,model);
 assert.match(el.innerHTML,/data-material-tab/);
 assert.match(el.innerHTML,/data-material-node/);
 assert.match(el.innerHTML,/0 rotas confirmadas/);
 el.handlers.click({target:{closest(s){return s==="[data-material-tab]"?{dataset:{materialTab:"relacoes"}}:null}}});
 assert.equal((el.innerHTML.match(/class="material-relation"/g)||[]).length,15);
 el.handlers.click({target:{closest(s){return s==="[data-material-tab]"?{dataset:{materialTab:"lacunas"}}:null}}});
 assert.equal((el.innerHTML.match(/class="material-gaps"/g)||[]).length,1);
 assert.equal((el.innerHTML.match(/<article>/g)||[]).length,12);
});
