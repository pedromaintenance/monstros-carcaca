 assert.match(html,/initChronocartography\(\$\("chronocartography"\),state\.chrono\)/);
 assert.match(ci,/data\/atlas\/cronocartografia-ciclo40\.json/);
 assert.match(ui,/data-chrono-phase/);
 assert.match(ui,/data-chrono-event/);
