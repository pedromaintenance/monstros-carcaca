test("XLV: impedir canonização, geografia falsa, espécie sem página e habitats tratados como cidades",()=>{
 const check=(label,mutate,re)=>assert.throws(()=>build(changed(mutate)),re,label);
 check("aprovado",x=>x.aprovacao_autoral=true,/proposta não canônica/);
 check("assentamento aprovado",x=>x.assentamentos[0].aprovacao_autoral=true,/classificação/);
 check("coordenadas",x=>x.assentamentos[0].geometria={lat:0,long:0},/classificação/);
 check("rota",x=>x.assentamentos[0].rota="Drakport",/classificação/);
 check("população",x=>x.assentamentos[0].populacao=350,/classificação/);
 check("efeito automático",x=>x.assentamentos[0].conexao_automatica=true,/classificação/);
 check("identidade perdida",x=>x.assentamentos[0].governo_e_organizacao="",/identidade/);
 check("páginas falsas",x=>x.assentamentos[0].paginas=[999],/identidade/);
 check("macroambiente",x=>x.assentamentos[0].ambiente_id="amb:eldroth",/macroambiente/);
 check("setor ilegítimo",x=>x.assentamentos[0].setor="caatinga",/classificação/);
 check("duplicata primeiro lote",x=>x.assentamentos[0].nome="A Orla das Cestas Sussurrantes",/nomeado duas vezes/);
 check("duplicata no segundo lote",x=>x.assentamentos[1].id=x.assentamentos[0].id,/Identificador duplicado/);
 check("ausência de assentamento",x=>x.assentamentos.pop(),/nove comunidades/);
 check("habitat vira cidade",x=>x.habitats[0].conta_como_assentamento=true,/Habitat contado/);
 check("habitat vivo confirmado",x=>x.habitats[0].vida_sapiente_confirmada=true,/Habitat contado/);
 check("habitat denso inventado",x=>x.habitats[0].densidade=250,/Habitat contado/);
 check("habitat remove",x=>x.habitats.pop(),/dez lugares ecológicos/);
 check("rota falsa",x=>x.premissas_de_rede[0].estado="rota_confirmada",/Eixo documental/);
 check("total aprovado",x=>x.notas_densidade.total_aprovado=3,/números das propostas/);
});
